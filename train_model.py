"""Train a demonstration model and save it for the Flask API to use."""
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
from sklearn.tree import DecisionTreeClassifier

BASE_DIR = Path(__file__).resolve().parent
MODEL_PATH = BASE_DIR / "student_pass_model.joblib"


def create_demo_dataset(n_samples: int = 600, random_state: int = 42) -> pd.DataFrame:
    """Create synthetic data for classroom demonstration only."""
    rng = np.random.default_rng(random_state)
    study_hours = rng.uniform(0, 10, n_samples).round(1)
    attendance = rng.uniform(40, 100, n_samples).round(1)

    # Demonstration rule: study hours and attendance both affect the label.
    # These labels are invented for teaching and are not real student outcomes.
    pass_condition = (
        ((study_hours >= 4.0) & (attendance >= 70.0))
        | ((study_hours >= 7.0) & (attendance >= 55.0))
        | ((study_hours >= 2.0) & (attendance >= 92.0))
    )
    labels = np.where(pass_condition, "Pass", "Fail")

    return pd.DataFrame({
        "study_hours": study_hours,
        "attendance_percentage": attendance,
        "result": labels,
    })


def main() -> None:
    data = create_demo_dataset()
    X = data[["study_hours", "attendance_percentage"]]
    y = data["result"]

    model = DecisionTreeClassifier(max_depth=5, random_state=42)
    model.fit(X, y)

    joblib.dump(model, MODEL_PATH)
    print(f"Model trained and saved to: {MODEL_PATH}")
    print(f"Training rows: {len(data)}")
    print("\nThree demonstration predictions (generated by the trained model):")

    test_students = pd.DataFrame([
        {"study_hours": 1.0, "attendance_percentage": 50.0},
        {"study_hours": 5.0, "attendance_percentage": 85.0},
        {"study_hours": 8.0, "attendance_percentage": 95.0},
    ])
    predictions = model.predict(test_students)
    for index, row in test_students.iterrows():
        print(
            f"Study hours={row['study_hours']:.1f}, "
            f"attendance={row['attendance_percentage']:.1f}% "
            f"=> {predictions[index]}"
        )


if __name__ == "__main__":
    main()
