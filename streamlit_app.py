from pathlib import Path
import joblib
import pandas as pd
import streamlit as st

BASE_DIR = Path(__file__).resolve().parent
MODEL_PATH = BASE_DIR / "student_pass_model.joblib"

st.set_page_config(page_title="Student Pass Predictor", page_icon="🎓")

if not MODEL_PATH.exists():
    st.error("Model file not found. Run train_model.py first.")
    st.stop()

model = joblib.load(MODEL_PATH)

st.title("🎓 Student Pass Predictor")
st.write("Predict whether a student is likely to pass based on study hours.")

student_name = st.text_input("Student Name", placeholder="Enter student name")
study_hours = st.number_input(
    "Study Hours",
    min_value=0.0,
    max_value=24.0,
    value=5.0,
    step=0.5,
)

if st.button("Predict", type="primary"):
    if not student_name.strip():
        st.warning("Please enter the student's name.")
    else:
        prediction = int(model.predict([[study_hours]])[0])
        label = "Pass" if prediction == 1 else "Fail"

        if prediction == 1:
            st.success(f"{student_name.strip()} is predicted to **PASS**.")
        else:
            st.error(f"{student_name.strip()} is predicted to **FAIL**.")

        st.info(
            f"The prediction was generated by the saved machine-learning model using "
            f"{study_hours:g} study hour(s) as the input. The model was loaded from "
            "student_pass_model.joblib, so it did not need to be retrained for this prediction."
        )

        # Bonus: compare study hours against predicted class.
        chart_data = pd.DataFrame({
            "Study Hours": [study_hours],
            "Predicted Class": [prediction],
        })
        st.subheader("Prediction Chart")
        st.bar_chart(chart_data.set_index("Study Hours"))
