from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import streamlit as st

MODEL_PATH = Path(__file__).resolve().parent / "student_pass_model.joblib"

st.set_page_config(page_title="Student Pass Predictor", page_icon="🎓")


@st.cache_resource
def load_model():
    return joblib.load(MODEL_PATH)


model = load_model()

st.title("🎓 Student Pass Predictor")

with st.expander("About this app: Streamlit Interface"):
    st.write(
        "**Definition:** Streamlit is a Python framework used to create interactive web "
        "applications for data science and Machine Learning projects without requiring "
        "extensive frontend development."
    )
    st.write(
        "**Explanation:** Streamlit allows us to create a user-friendly interface where "
        "users can enter data, click buttons, and view the predictions generated by a "
        "Machine Learning model."
    )

student_name = st.text_input("Student name")

study_hours = st.number_input("Study hours per day", min_value=0.0, max_value=24.0, value=4.0, step=0.5)

if st.button("Predict"):
    if not student_name.strip():
        st.warning("Please enter the student's name.")
    else:
        x = np.array([[study_hours]])
        chance = float(model.predict_proba(x)[0][1])
        will_pass = int(model.predict(x)[0]) == 1

        if will_pass:
            st.success(f"{student_name} is likely to PASS.")
        else:
            st.error(f"{student_name} is likely to FAIL.")
        st.write(f"Chance of passing: **{chance:.0%}**")

        st.info(
            "The prediction was generated by a saved Machine Learning model that learned "
            f"from past examples of study hours and results. For {study_hours} hour(s) it "
            f"estimated a {chance:.0%} chance of passing. A chance of 50% or more is Pass; "
            "lower is Fail."
        )

      
        grid = np.arange(0, 12.5, 0.5)
        chart_df = pd.DataFrame(
            {"Predicted class (1=Pass, 0=Fail)": model.predict(grid.reshape(-1, 1))},
            index=pd.Index(grid, name="Study hours"),
        )
        st.subheader("Study hours vs predicted class")
        st.bar_chart(chart_df)
        st.caption(f"{student_name} entered {study_hours} hour(s) of study.")