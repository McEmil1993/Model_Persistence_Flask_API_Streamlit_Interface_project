import streamlit as st
import joblib
import numpy as np
import pandas as pd

# Load model
model = joblib.load('student_pass_model.joblib')

st.set_page_config(page_title="Student Pass Predictor")
st.title("Student Pass Prediction")

# Inputs
student_name = st.text_input("Student Name")
study_hours = st.number_input(
    "Study Hours",
    min_value=0.0,
    max_value=24.0,
    value=5.0,
    step=0.5
)

# Prediction button
if st.button("Predict"):
    if student_name.strip() == "":
        st.warning("Please enter the student name.")
    else:
        prediction = model.predict([[study_hours]])[0]
        probability = model.predict_proba([[study_hours]])[0][1]
        result = "Pass" if prediction == 1 else "Fail"

        # Result message
        st.success(f"{student_name}, the predicted result is: **{result}**")
        st.write(f"Probability of passing: **{probability:.2%}**")

        # Short explanation
        st.info(
            "This prediction was generated by a Logistic Regression model trained on study hours. "
            "The model learned a mathematical relationship between study hours and pass/fail outcomes. "
            "It uses that relationship to estimate the result for the given study hours."
        )

        # Bonus: Chart comparing study hours with predicted class
        hours_range = np.linspace(0, 12, 50).reshape(-1, 1)
        preds = model.predict(hours_range)

        chart_data = pd.DataFrame({
            'Study Hours': hours_range.flatten(),
            'Predicted Class': preds
        })

        st.subheader("Study Hours vs Predicted Class")
        st.line_chart(chart_data.set_index('Study Hours'))
        st.caption("0 = Fail, 1 = Pass")
