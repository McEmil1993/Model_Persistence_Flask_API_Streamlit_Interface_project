from pathlib import Path

import altair as alt
import joblib
import numpy as np
import pandas as pd
import streamlit as st

MODEL_FILE = Path(__file__).resolve().parent / "student_pass_model.joblib"

st.set_page_config(page_title="Student Pass Predictor", page_icon="🎓")


@st.cache_resource
def load_model():
    return joblib.load(MODEL_FILE)


def heatmap(model, user_hours):
    """Bonus: heatmap comparing study hours with the predicted class."""
    grid = np.arange(0, 12.5, 0.5)
    predicted = model.predict(grid.reshape(-1, 1))
    rows = []
    for h, c in zip(grid, predicted):
        for label in ("Fail", "Pass"):
            rows.append({
                "Study hours": float(h),
                "Class": label,
                "Predicted": 1 if (label == "Pass") == (c == 1) else 0,
            })
    df = pd.DataFrame(rows)

    cells = alt.Chart(df).mark_rect(stroke="white").encode(
        x=alt.X("Study hours:O", title="Study hours"),
        y=alt.Y("Class:N", sort=["Pass", "Fail"], title="Predicted class"),
        color=alt.Color("Predicted:Q", legend=None,
                        scale=alt.Scale(domain=[0, 1], range=["#f0f0f0", "#1f77b4"])),
        tooltip=["Study hours", "Class"],
    )
    # a red triangle marks the closest column to the hours that were entered
    nearest = float(grid[np.abs(grid - user_hours).argmin()])
    marker = alt.Chart(pd.DataFrame({"Study hours": [nearest], "Class": ["Pass"]})).mark_point(
        shape="triangle-down", size=250, filled=True, color="red", yOffset=-24
    ).encode(x="Study hours:O", y=alt.Y("Class:N", sort=["Pass", "Fail"]))
    return (cells + marker).properties(height=140)


model = load_model()

st.title("Student Pass Predictor")

student_name = st.text_input("Student name")

study_hours = st.number_input("Study hours per day", min_value=0.0, max_value=24.0, value=4.0, step=0.5)

if st.button("Predict"):
    if not student_name.strip():
        st.warning("Please enter the student's name.")
    else:
        x = np.array([[study_hours]])
        chance = float(model.predict_proba(x)[0][1])
        will_pass = int(model.predict(x)[0]) == 1

        if will_pass:
            st.success(f"{student_name} is likely to PASS.")
        else:
            st.error(f"{student_name} is likely to FAIL.")
        st.write(f"Chance of passing: **{chance:.0%}**")

        st.info(
            "The prediction was generated by a saved Machine Learning model that learned "
            f"from past examples of study hours and results. For {study_hours} hour(s) it "
            f"estimated a {chance:.0%} chance of passing. A chance of 50% or more is Pass; "
            "lower is Fail."
        )

        st.subheader("Study hours vs predicted class")
        st.altair_chart(heatmap(model, study_hours), width="stretch")
        st.caption("Blue cells show which class the model predicts for each study-hours value. "
                   f"The red triangle marks {student_name}'s input ({study_hours} hour(s)).")