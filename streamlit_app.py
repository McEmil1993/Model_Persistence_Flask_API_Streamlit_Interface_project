
import streamlit as st
import joblib
import pandas as pd

# Load the saved model
model = joblib.load("student_pass_model.joblib")

st.set_page_config(
    page_title="Student Pass Predictor",
    page_icon="🎓",
    layout="centered"
)

st.title("🎓 Student Pass Predictor")
st.write(
    "Enter a student's information to predict "
    "their possible academic outcome."
)

# Student inputs
student_name = st.text_input("Student Name")

study_hours = st.number_input(
    "Study Hours per Day",
    min_value=0.0,
    max_value=24.0,
    value=5.0,
    step=0.5
)

attendance = st.number_input(
    "Attendance Percentage",
    min_value=0.0,
    max_value=100.0,
    value=85.0,
    step=1.0
)

# Prediction button
if st.button("Predict Student Outcome"):
    if not student_name.strip():
        st.warning("Please enter the student's name.")
    else:
        # Use the same feature order as model training
        prediction = int(
            model.predict([[study_hours, attendance]])[0]
        )

        result = "Pass" if prediction == 1 else "Fail"

        st.subheader("Prediction Result")
        st.write(f"**Student:** {student_name}")
        st.write(f"**Study Hours:** {study_hours}")
        st.write(f"**Attendance:** {attendance}%")

        if prediction == 1:
            st.success(f"Predicted Class: {result}")
        else:
            st.error(f"Predicted Class: {result}")

        st.info(
            "The result was generated by loading the trained "
            "machine learning model and supplying the student's "
            "study hours and attendance percentage. The model "
            "compares these inputs with patterns learned from "
            "the training data. This is an estimate, not a "
            "guarantee of academic performance."
        )

        # Bonus chart: compare the entered values
        chart_data = pd.DataFrame({
            "Input": ["Study Hours", "Attendance (%)"],
            "Value": [study_hours, attendance]
        })

        st.subheader("Student Input Comparison")
        st.bar_chart(
            chart_data.set_index("Input")
        )
