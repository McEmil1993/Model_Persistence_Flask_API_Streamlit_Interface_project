import streamlit as st
import joblib
import matplotlib.pyplot as plt

st.set_page_config(
    page_title="Student Dashboard",
    page_icon="🎓",
    layout="wide"
)

model = joblib.load("student_pass_model.joblib")

st.markdown("""
<style>
.stApp { background: #f4f7fb; }
[data-testid="stSidebar"] { background: #172554; }
[data-testid="stSidebar"] * { color: white; }
h1, h2, h3 { color: #172554; }
[data-testid="stMetric"] {
    background: white;
    padding: 20px;
    border-radius: 12px;
    border: 1px solid #e2e8f0;
}
.stButton button {
    background: #1d4ed8;
    color: white;
    width: 100%;
    border-radius: 8px;
    height: 45px;
    font-weight: bold;
}
</style>
""", unsafe_allow_html=True)

# Sidebar
with st.sidebar:
    st.title("🎓 Student Portal")
    st.write("---")
    page = st.radio(
        "Navigation",
        ["Dashboard", "Predict Student"]
    )
    st.write("---")
    st.caption("Student Pass Prediction System")

# Dashboard
st.title("📊 Student Performance Dashboard")
st.write("Machine learning predictions based on study hours.")
st.write("")

if "history" not in st.session_state:
    st.session_state.history = []

# Summary cards
total = len(st.session_state.history)
passed = sum(x["prediction"] == "Pass"
             for x in st.session_state.history)
failed = total - passed

col1, col2, col3 = st.columns(3)
col1.metric("Total Predictions", total)
col2.metric("Predicted Pass", passed)
col3.metric("Predicted Fail", failed)

st.write("")

if page == "Dashboard":
    left, right = st.columns([1, 1])

    with left:
        st.subheader("👨‍🎓 Predict Student Result")

        with st.form("prediction_form"):
            name = st.text_input("Student Name")
            hours = st.number_input(
                "Study Hours per Day",
                min_value=0.0,
                max_value=24.0,
                value=5.0,
                step=0.5
            )
            submitted = st.form_submit_button("Predict Result")

        if submitted:
            if not name.strip():
                st.warning("Please enter the student's name.")
            else:
                prediction = int(model.predict([[hours]])[0])
                result = "Pass" if prediction == 1 else "Fail"

                st.session_state.history.append({
                    "name": name.strip(),
                    "hours": hours,
                    "prediction": result
                })

                st.session_state.last_result = {
                    "name": name.strip(),
                    "hours": hours,
                    "prediction": result
                }

    with right:
        st.subheader("📈 Study Hours vs Predicted Class")

        hours_range = list(range(25))
        predictions = model.predict([[h] for h in hours_range])
        classes = [1 if p == 1 else 0 for p in predictions]

        fig, ax = plt.subplots(figsize=(7, 4))
        fig.patch.set_facecolor("white")
        ax.set_facecolor("white")

        ax.step(hours_range, classes, where="mid",
                linewidth=2, label="Model prediction")

        last = st.session_state.get("last_result")
        if last:
            ax.scatter(
                [last["hours"]],
                [1 if last["prediction"] == "Pass" else 0],
                s=100,
                label="Selected student"
            )

        ax.set_xlabel("Study Hours")
        ax.set_ylabel("Predicted Class")
        ax.set_yticks([0, 1], ["Fail", "Pass"])
        ax.set_xticks(range(0, 25, 2))
        ax.grid(alpha=0.25)
        ax.legend()
        st.pyplot(fig)
        plt.close(fig)

    # Latest result
    if "last_result" in st.session_state:
        result = st.session_state.last_result
        st.write("---")
        st.subheader("✅ Latest Prediction")

        st.write(f"**Student:** {result['name']}")
        st.write(f"**Study Hours:** {result['hours']} hours")

        if result["prediction"] == "Pass":
            st.success(f"Prediction: {result['prediction']}")
        else:
            st.error(f"Prediction: {result['prediction']}")

        st.info(
            "The prediction was generated by a trained machine "
            "learning model using study hours. It is an estimate, "
            "not a guarantee of the student's actual result."
        )

    # Prediction history
    st.write("---")
    st.subheader("📋 Prediction History")

    if st.session_state.history:
        st.dataframe(
            list(reversed(st.session_state.history)),
            use_container_width=True
        )
    else:
        st.caption("No predictions yet. Enter a student to get started.")

else:
    st.subheader("🔍 Predict a Student")

    with st.form("student_prediction"):
        name = st.text_input("Student Name")
        hours = st.number_input(
            "Study Hours",
            min_value=0.0,
            max_value=24.0,
            value=5.0,
            step=0.5
        )
        submitted = st.form_submit_button("Predict Result")

    if submitted:
        if not name.strip():
            st.warning("Please enter a student name.")
        else:
            prediction = int(model.predict([[hours]])[0])
            result = "Pass" if prediction == 1 else "Fail"

            st.session_state.history.append({
                "name": name.strip(),
                "hours": hours,
                "prediction": result
            })
            st.session_state.last_result = {
                "name": name.strip(),
                "hours": hours,
                "prediction": result
            }

            st.write(f"### Student: {name}")
            st.write(f"Study Hours: {hours}")

            if prediction == 1:
                st.success("Predicted Result: PASS")
            else:
                st.error("Predicted Result: FAIL")

            st.info(
                "This prediction uses study hours as the model input. "
                "The result may differ from the student's actual outcome."
            )

