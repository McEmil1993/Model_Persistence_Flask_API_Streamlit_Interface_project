from pathlib import Path

import joblib
import streamlit as st

from student_model import (
    EXAMPLE_PASS_LABELS,
    EXAMPLE_STUDY_HOURS,
    StudentPassModel,
    leave_one_out_metrics,
)


MODEL_PATH = Path(__file__).with_name("student_pass_model.joblib")


@st.cache_resource
def load_model() -> StudentPassModel:
    return joblib.load(MODEL_PATH)


st.set_page_config(page_title="Student Pass Predictor", page_icon="📘")
st.title("Student Pass Predictor")

if not MODEL_PATH.exists():
    st.error("Model file not found. Run `python train_model.py` before starting Streamlit.")
    st.stop()

student_name = st.text_input("Student name")
study_hours = st.number_input("Study hours", min_value=0.0, max_value=24.0, value=5.0, step=0.5)

if st.button("Predict", type="primary"):
    model = load_model()
    predicted_class = int(model.predict([[study_hours]])[0])
    pass_probability = model.predict_proba([[study_hours]])[0][1]
    fail_probability = 1 - pass_probability
    prediction = "Pass" if predicted_class == 1 else "Fail"
    display_name = student_name.strip() or "This student"

    st.subheader(f"{display_name}: {prediction}")
    pass_metric, fail_metric = st.columns(2)
    pass_metric.metric("Pass probability", f"{pass_probability:.1%}")
    fail_metric.metric("Fail probability", f"{fail_probability:.1%}")
    st.progress(pass_probability, text="Estimated probability of passing")
    st.write(
        f"The prediction was generated by a saved logistic-regression model using "
        f"{study_hours:g} study hours. The model was trained on example study-hours data; "
        "it does not use attendance. These probabilities are estimates from the demo model, "
        "not validated real-world chances."
    )

    accuracy, brier_score = leave_one_out_metrics(EXAMPLE_STUDY_HOURS, EXAMPLE_PASS_LABELS)
    with st.expander("How accurate are these predictions?", expanded=True):
        accuracy_metric, brier_metric = st.columns(2)
        accuracy_metric.metric("Leave-one-out accuracy", f"{accuracy:.1%}")
        brier_metric.metric("Brier score", f"{brier_score:.3f}", help="Lower is better; 0 is a perfect probability score.")
        st.caption(
            "Accuracy is the share of held-out examples classified correctly at the 50% threshold. "
            "The Brier score measures how close predicted pass probabilities are to the actual 0/1 outcomes. "
            "Both are calculated from only 11 synthetic examples, so they demonstrate evaluation methods "
            "and do not establish real-world accuracy or probability calibration."
        )

    hours_grid = [step / 2 for step in range(49)]
    pass_probabilities = [probabilities[1] for probabilities in model.predict_proba([[hours] for hours in hours_grid])]
    st.line_chart(
        {"Study hours": hours_grid, "Pass probability": pass_probabilities},
        x="Study hours",
        y="Pass probability",
    )
    st.caption("The model predicts Pass when the estimated pass probability is at least 50%.")