"""Streamlit interface for the persisted student outcome model."""

from pathlib import Path

import joblib
import matplotlib.pyplot as plt
import streamlit as st


MODEL_PATH = Path(__file__).resolve().parent / "student_pass_model.joblib"

st.set_page_config(page_title="Student Pass Predictor", page_icon="🎓")
st.title("Student Pass Predictor")
st.write("Enter a student's details and predict the likely result using the saved model.")

if not MODEL_PATH.exists():
    st.error("The model has not been trained yet. Run `python train_model.py` first.")
    st.stop()

model = joblib.load(MODEL_PATH)
student_name = st.text_input("Student name")
study_hours = st.number_input("Study hours", min_value=0.0, max_value=24.0, value=4.0, step=0.5)
attendance = st.number_input("Attendance percentage", min_value=0.0, max_value=100.0, value=80.0, step=1.0)

if st.button("Predict"):
    prediction = int(model.predict([[study_hours, attendance]])[0])
    label = "Pass" if prediction == 1 else "Fail"
    name = student_name.strip() or "The student"
    st.success(f"{name}: {label}")
    st.caption(
        "The result was generated by loading the persisted model and providing it "
        "with study hours and attendance percentage."
    )

    figure, axis = plt.subplots()
    axis.bar(["Study hours", "Predicted class"], [study_hours, prediction])
    axis.set_title("Input study hours vs. predicted class")
    axis.set_ylim(0, max(2, study_hours + 1))
    st.pyplot(figure)
