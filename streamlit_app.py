from pathlib import Path

import joblib
import pandas as pd
import streamlit as st


MODEL_PATH = Path(__file__).with_name("student_pass_model.joblib")

st.title("Student Pass Predictor")
st.write("Enter a student's name and study hours to see the model's prediction.")

if not MODEL_PATH.is_file():
    st.error("The trained model was not found. Run `python train_model.py` first.")
    st.stop()

model = joblib.load(MODEL_PATH)
student_name = st.text_input("Student name")
study_hours = st.number_input(
    "Study hours",
    min_value=0.0,
    max_value=10.0,
    value=5.0,
    step=0.5,
)

if st.button("Predict", type="primary"):
    prediction = int(model.predict([[study_hours]])[0])
    predicted_class = "Pass" if prediction == 1 else "Fail"
    name = student_name.strip() or "The student"

    st.success(f"{name} is predicted to {predicted_class.lower()}.")
    st.write(
        f"The prediction was generated by applying the saved model to "
        f"{study_hours:g} study hours. This model was trained using study hours "
        "only; it does not use attendance or personal student data."
    )

    hours = [value / 2 for value in range(21)]
    chart_data = pd.DataFrame(
        {
            "Study hours": hours,
            "Predicted class (0 = Fail, 1 = Pass)": [
                int(model.predict([[value]])[0]) for value in hours
            ],
        }
    )
    st.subheader("Study hours and predicted class")
    st.line_chart(chart_data, x="Study hours")
    st.caption(
        f"At {study_hours:g} study hours, the model predicts "
        f"{predicted_class.lower()} (class {prediction})."
    )
