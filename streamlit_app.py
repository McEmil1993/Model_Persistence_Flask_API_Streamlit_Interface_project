# Exercise 3 - Streamlit Interface (with Bonus chart)
from pathlib import Path

import joblib
import numpy as np
import pandas as pd
import streamlit as st

MODEL_PATH = Path(__file__).parent.resolve() / "student_pass_model.joblib"

st.set_page_config(page_title="Student Pass Predictor", page_icon="✅")


@st.cache_resource
def get_model():
    return joblib.load(MODEL_PATH)


def chart_data(model, user_hours):
    """Bonus data: study hours vs predicted class (0 = Fail, 1 = Pass)."""
    grid = np.arange(0, 12.5, 0.5)
    predicted = model.predict(grid.reshape(-1, 1))
    df = pd.DataFrame({
        "Study hours": grid,
        "Predicted class (1=Pass, 0=Fail)": predicted,
        "Point": "Model prediction",
    })
    user_pred = model.predict(np.array([[user_hours]]))[0]
    me = pd.DataFrame({
        "Study hours": [user_hours],
        "Predicted class (1=Pass, 0=Fail)": [user_pred],
        "Point": "Your input",
    })
    return pd.concat([df, me], ignore_index=True)


model = get_model()

st.title("✅ Student Pass Predictor")

with st.sidebar:
    st.header("Student details")
    student = st.text_input("Student name")
    hours = st.number_input("Study hours per day", min_value=0.0, max_value=24.0, value=5.0, step=0.5)
    go = st.button("Predict")

st.write("Fill in the details on the left, then press **Predict**.")

if go:
    if not student.strip():
        st.warning("Please enter the student's name.")
    else:
        prob_pass = model.predict_proba(np.array([[hours]]))[0, 1]
        label = "PASS" if prob_pass >= 0.5 else "FAIL"

        # Result message
        if label == "PASS":
            st.success(f"{student} is likely to {label}.")
        else:
            st.error(f"{student} is likely to {label}.")
        st.progress(float(prob_pass), text=f"Chance of passing: {prob_pass:.0%}")

        # Short explanation
        st.info(
            "The prediction was generated by a model trained on past study hours and their "
            f"results. For {hours} hour(s) it found a {prob_pass:.0%} chance of passing; "
            "50% or higher is Pass, lower is Fail."
        )

        # Bonus chart
        st.subheader("Study hours vs predicted class")
        st.scatter_chart(
            chart_data(model, hours),
            x="Study hours",
            y="Predicted class (1=Pass, 0=Fail)",
            color="Point",
        )
        st.caption("Blue dots show the model's prediction for each study-hours value; "
                   "the other color marks the hours you entered.")